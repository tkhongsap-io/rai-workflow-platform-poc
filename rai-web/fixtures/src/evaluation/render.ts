// Document renderers of `qc-eval-synthetic@1` (W4b plan section 11.1): one EvalDocument row → bytes, over the
// builders in generate/{pdf,ooxml,png}.ts (Node built-ins only). Every document starts with the provenance
// preamble (sentinel, set and document id, the synthetic-data sentence; the Thai line in Thai documents). The
// renderer also returns each claim's locator in the W4-16 shape, so the labels can be checked for grounding
// without re-implementing any rule. Pure: the same row always yields the same bytes.

import type { AllowedMediaType } from '@rai/shared/schemas/artifacts';
import { FIXTURE_SENTINEL, FIXTURE_THAI_LINE, MEDIA_TYPE_BY_KIND } from '../data/documents/index.js';
import { buildDocx, buildXlsxWorkbook, columnName, type XlsxSheet } from '../generate/ooxml.js';
import { buildPdfDocument, type PdfPageSpec } from '../generate/pdf.js';
import { buildPng } from '../generate/png.js';
import type { Block, Claim, EvalDocument, EvalFormat, EvalLanguage, LabelLocator } from './types.js';
import {
  DEV_ANSWERS,
  DEV_KEY_ORDER,
  DEV_PAIR_SEPARATOR,
  DEV_QUESTIONS,
  DEV_SHEET_NAMES,
  type ClaimKey,
} from './vocabulary.js';

export const EVAL_SET_NAME = 'qc-eval-synthetic' as const;
export const EVAL_SET_VERSION = '1' as const;
export const EVAL_PROVENANCE_SENTENCE =
  'Synthetic evaluation document generated by rai-web/fixtures. Not a real document. Contains no real data.' as const;

export interface RenderedDocument {
  documentId: string;
  slot: EvalDocument['slot'];
  format: EvalFormat;
  filename: string;
  mediaType: AllowedMediaType;
  bytes: Buffer;
  /** One per claim, in document order; empty for a format the extractor cannot read. */
  claimLocators: LabelLocator[];
}

const MEDIA_KIND: Readonly<Record<EvalFormat, keyof typeof MEDIA_TYPE_BY_KIND>> = Object.freeze({
  docx: 'docx',
  docx_doctype: 'docx',
  xlsx: 'xlsx',
  pdf: 'pdf',
  pdf_flate: 'pdf',
  pdf_image: 'pdf',
  pdf_cid: 'pdf',
  pdf_broken_xref: 'pdf',
  png: 'png',
});

export function preambleLines(doc: EvalDocument): string[] {
  const lines = [
    `${FIXTURE_SENTINEL} ${EVAL_SET_NAME}@${EVAL_SET_VERSION} ${doc.documentId}`,
    EVAL_PROVENANCE_SENTENCE,
  ];
  if (doc.language === 'th') lines.push(FIXTURE_THAI_LINE);
  return lines;
}

function claimFields(claim: Claim, language: EvalLanguage): Record<ClaimKey, string | undefined> {
  return {
    item: claim.ref,
    question: DEV_QUESTIONS[language][claim.item],
    answer: DEV_ANSWERS[language][claim.answer],
    metric: claim.metric,
    value: claim.value,
    denominator: claim.denominator,
    threshold: claim.threshold,
    evidence: claim.evidence,
    tier: claim.tier,
  };
}

/** DOCX paragraph or PDF line: `key: value` pairs in the dev key order, joined by `; `. */
export function claimLine(claim: Claim, language: EvalLanguage): string {
  const fields = claimFields(claim, language);
  return DEV_KEY_ORDER.flatMap((key) => (fields[key] === undefined ? [] : [`${key}: ${fields[key]}`])).join(
    DEV_PAIR_SEPARATOR,
  );
}

/** XLSX data row: one column per key in the dev order; an absent field is an empty cell. */
export function claimRow(claim: Claim, language: EvalLanguage): Array<string | null> {
  const fields = claimFields(claim, language);
  return DEV_KEY_ORDER.map((key) => fields[key] ?? null);
}

function blockLine(block: Block, language: EvalLanguage): string {
  return 'claim' in block ? claimLine(block.claim, language) : block.text;
}

/** Page 1 gets the preamble; the rest as written. */
function linesByPage(doc: EvalDocument): string[][] {
  return doc.pages.map((page, i) => [
    ...(i === 0 ? preambleLines(doc) : []),
    ...page.map((b) => blockLine(b, doc.language)),
  ]);
}

function renderDocx(
  doc: EvalDocument,
  options: { doctype?: boolean },
): {
  bytes: Buffer;
  locators: LabelLocator[];
} {
  const paragraphs: string[] = [...preambleLines(doc)];
  const locators: LabelLocator[] = [];
  for (const block of doc.pages.flat()) {
    paragraphs.push(blockLine(block, doc.language));
    if ('claim' in block) locators.push({ kind: 'section', index: paragraphs.length });
  }
  return { bytes: buildDocx(paragraphs, options), locators };
}

function renderXlsx(doc: EvalDocument): { bytes: Buffer; locators: LabelLocator[] } {
  const names = DEV_SHEET_NAMES[doc.language];
  if (doc.pages.length > names.length) throw new Error(`${doc.documentId}: at most ${names.length} sheets`);
  const answerColumn = columnName(DEV_KEY_ORDER.indexOf('answer'));
  const locators: LabelLocator[] = [];
  const sheets: XlsxSheet[] = doc.pages.map((page, i) => {
    const rows: Array<Array<string | null>> = i === 0 ? preambleLines(doc).map((l) => [l]) : [];
    let headerWritten = false;
    for (const block of page) {
      if (!('claim' in block)) {
        rows.push([block.text]);
        continue;
      }
      if (!headerWritten) {
        rows.push([...DEV_KEY_ORDER]);
        headerWritten = true;
      }
      rows.push(claimRow(block.claim, doc.language));
      locators.push({ kind: 'cell', sheetIndex: i + 1, cell: `${answerColumn}${rows.length}` });
    }
    return { name: names[i]!, rows };
  });
  const bytes = buildXlsxWorkbook({
    title: preambleLines(doc)[0]!,
    sheets,
    sharedStrings: true,
    method: 'deflate',
  });
  return { bytes, locators };
}

function renderPdf(doc: EvalDocument): { bytes: Buffer; locators: LabelLocator[] } {
  const pages = linesByPage(doc);
  const locators: LabelLocator[] = [];
  doc.pages.forEach((page, i) => {
    for (const block of page) if ('claim' in block) locators.push({ kind: 'page', page: i + 1 });
  });
  const title = preambleLines(doc)[0]!;
  const commentLines = [title];
  let specs: PdfPageSpec[];
  switch (doc.format) {
    case 'pdf_image':
      specs = pages.map(() => ({ kind: 'image' }));
      break;
    case 'pdf_cid':
      specs = pages.map((lines) => ({ kind: 'cid', lines }));
      break;
    default:
      specs = pages.map((lines) => ({ kind: 'text', lines }));
  }
  const bytes = buildPdfDocument({
    title,
    commentLines,
    pages: specs,
    compression: doc.format === 'pdf_flate' ? 'flate' : 'none',
    brokenXref: doc.format === 'pdf_broken_xref',
  });
  const readable = doc.format === 'pdf' || doc.format === 'pdf_flate';
  return { bytes, locators: readable ? locators : [] };
}

function renderPng(doc: EvalDocument): Buffer {
  // A scan: the lines exist only in a tEXt comment (never extracted; no OCR, decision 8). tEXt is Latin-1, so a
  // non-ASCII line is left out; the Thai line goes in the iTXt chunk as in slice1-synthetic.
  const lines = linesByPage(doc)
    .flat()
    .filter((l) => /^[\x20-\x7e]*$/.test(l));
  return buildPng({ comment: lines.join('\n'), thaiLine: FIXTURE_THAI_LINE });
}

export function renderDocument(doc: EvalDocument): RenderedDocument {
  let bytes: Buffer;
  let locators: LabelLocator[] = [];
  switch (doc.format) {
    case 'docx':
      ({ bytes, locators } = renderDocx(doc, {}));
      break;
    case 'docx_doctype':
      ({ bytes } = renderDocx(doc, { doctype: true }));
      break;
    case 'xlsx':
      ({ bytes, locators } = renderXlsx(doc));
      break;
    case 'png':
      bytes = renderPng(doc);
      break;
    default:
      ({ bytes, locators } = renderPdf(doc));
  }
  return {
    documentId: doc.documentId,
    slot: doc.slot,
    format: doc.format,
    filename: doc.filename,
    mediaType: MEDIA_TYPE_BY_KIND[MEDIA_KIND[doc.format]],
    bytes,
    claimLocators: locators,
  };
}
